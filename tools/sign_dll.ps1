<#
  sign_dll.ps1 - self-sign the mod DLL with a free, self-generated code-signing certificate.

  This is a REAL signature, generated by and belonging to you. It is not issued by a
  certificate authority, so Windows shows the publisher as unverified - that is expected and
  honest for a free self-signed cert. What it provides: proof the file has not been altered
  since you built it, plus a named publisher, which quiets many antivirus heuristics that flag
  unsigned, unlabelled DLLs.

  Usage:  powershell -ExecutionPolicy Bypass -File tools\sign_dll.ps1 [path\to\FinalFoliage.dll]
  Default target: dll\FinalFoliage.dll
#>
param(
    [string]$Target = (Join-Path $PSScriptRoot "..\dll\FinalFoliage.dll"),
    [string]$Subject = "CN=XaviFlorit, O=Final Foliage Reenabled"
)
$ErrorActionPreference = "Stop"
$Target = (Resolve-Path $Target).Path

# 1. Find an existing code-signing cert with this subject, or make one (valid 10 years).
# match by the Code Signing EKU OID (1.3.6.1.5.5.7.3.3) - locale-independent, unlike the friendly name
$cert = Get-ChildItem Cert:\CurrentUser\My |
        Where-Object { $_.Subject -eq $Subject -and ($_.EnhancedKeyUsageList.ObjectId -contains "1.3.6.1.5.5.7.3.3") } |
        Sort-Object NotAfter -Descending | Select-Object -First 1
if (-not $cert) {
    Write-Host "Creating a new self-signed code-signing certificate..."
    $cert = New-SelfSignedCertificate -Type CodeSigningCert -Subject $Subject `
        -CertStoreLocation Cert:\CurrentUser\My -KeyExportPolicy Exportable `
        -KeyUsage DigitalSignature -KeyAlgorithm RSA -KeyLength 3072 `
        -HashAlgorithm SHA256 -NotAfter (Get-Date).AddYears(10)
}
Write-Host ("Certificate: {0}  (thumbprint {1})" -f $cert.Subject, $cert.Thumbprint)
# always keep the public cert (safe to share/commit) in sync with the signer; private key stays in your store
Export-Certificate -Cert $cert -FilePath (Join-Path $PSScriptRoot "FinalFoliage-codesign.cer") | Out-Null

# 2. Sign + RFC3161 timestamp (so the signature stays valid after the cert expires).
$ts = "http://timestamp.digicert.com"
$sig = Set-AuthenticodeSignature -FilePath $Target -Certificate $cert `
        -HashAlgorithm SHA256 -TimestampServer $ts
# A self-signed signature embeds fine but reports 'UnknownError' (untrusted root) on any machine
# that did not create the cert - that is expected, not a failure. Only a missing/broken signature
# (no SignerCertificate) is a real error.
if (-not $sig.SignerCertificate) { throw "Signing failed: $($sig.StatusMessage)" }
if ($sig.Status -eq "Valid") {
    Write-Host ("Signed + trusted on this machine: {0}" -f (Split-Path $Target -Leaf))
} else {
    Write-Host ("Signed + timestamped (self-signed, shows as unverified publisher - expected): {0}" -f (Split-Path $Target -Leaf))
}
