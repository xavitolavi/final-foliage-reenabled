"""Generate dll/windpatch_data.inc: the wind-distance code cave from patch_wind.py, for the DLL to write into
the game's memory at startup (ff7rebirth_.exe on disk is never modified).

The cave only uses RIP-relative addressing, so bytes built for the default image base work at any ASLR base.
usage: python tools/gen_windpatch.py      (needs an unmodified ff7rebirth_.exe: FF7R_GAME or FF7R_ORIGINAL_EXE)"""
import os, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import patch_wind as pw  # noqa: E402

GAME = os.environ.get('FF7R_GAME', r'C:\Program Files (x86)\Steam\steamapps\common\FINAL FANTASY VII REBIRTH')
w64 = os.path.join(GAME, r'End\Binaries\Win64')
EXE = next((p for p in (os.environ.get('FF7R_ORIGINAL_EXE', ''),
                        os.path.join(w64, 'ff7rebirth_.exe.finalfoliage-original'),
                        os.path.join(w64, 'ff7rebirth_.exe')) if p and os.path.exists(p)), None)
assert EXE, 'set FF7R_GAME (game folder) or FF7R_ORIGINAL_EXE (unmodified ff7rebirth_.exe)'
data = open(EXE, 'rb').read()
pe = pw.PE(bytearray(data))
assert pe.base == 0x140000000, hex(pe.base)
o = pe.va2off(pw.HOOK_VA)
assert data[o:o + len(pw.HOOK_ORIG)] == pw.HOOK_ORIG, 'exe is modified or a different game build'
t = pe.secs['.text']
assert t['vsz'] == pw.TEXT_VSIZE_ORIG, 'exe is modified or a different game build'

SENTINEL = 0x7A5C3E1D   # placeholder limit, located below and replaced at runtime
cave_va = pe.base + t['va'] + pw.CAVE_TEXT_OFFSET
cave = pw.build_cave(cave_va, SENTINEL)
sent = struct.pack('<I', SENTINEL)
lim = [i for i in range(len(cave) - 3) if cave[i:i + 4] == sent]
assert len(lim) == 2, lim
assert pw.CAVE_TEXT_OFFSET + len(cave) <= pw.LOADER_TEXT_OFFSET

rva = lambda va: va - pe.base
hexs = lambda b: ', '.join('0x%02X' % x for x in b)
out = os.path.join(ROOT, 'dll', 'windpatch_data.inc')
with open(out, 'w', newline='\r\n') as f:
    f.write('// generated by tools/gen_windpatch.py - do not edit (game build sha256 752807180c4e...)\n')
    f.write('static constexpr uint32_t WP_HOOK_RVA = 0x%X;\n' % rva(pw.HOOK_VA))
    f.write('static const uint8_t WP_HOOK_ORIG[%d] = { %s };\n' % (len(pw.HOOK_ORIG), hexs(pw.HOOK_ORIG)))
    f.write('static constexpr uint32_t WP_CAVE_RVA = 0x%X;\n' % (t['va'] + pw.CAVE_TEXT_OFFSET))
    f.write('static const uint8_t WP_CAVE[%d] = {\n' % len(cave))
    for i in range(0, len(cave), 16):
        f.write('    %s,\n' % hexs(cave[i:i + 16]))
    f.write('};\n')
    f.write('static constexpr uint32_t WP_LIMIT_OFF[2] = { %d, %d };   // offsets of the two limit constants in WP_CAVE\n' % tuple(lim))
    f.write('// an earlier test installer patched the exe on disk: entry point -> stub that LoadLibraryA("FinalFoliage.dll")\n')
    f.write('static constexpr uint32_t WP_V10_STUB_RVA = 0x%X;\n' % (t['va'] + pw.LOADER_TEXT_OFFSET))
    f.write('static constexpr uint32_t WP_ENTRY_RVA = 0x%X;\n' % pw.ENTRY_RVA_ORIG)
print('wrote', out, '- cave', len(cave), 'bytes, limits at', lim)
