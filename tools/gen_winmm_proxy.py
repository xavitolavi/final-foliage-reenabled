"""Generate the winmm.dll proxy sources from the system winmm.dll export table.

The game imports WINMM.dll, so Windows loads a winmm.dll placed next to ff7rebirth_.exe at startup.
Every winmm export is re-exported (same names and ordinals) as a one-instruction stub that jumps to the
real function in System32\\winmm.dll, resolved once in DllMain.

usage: python tools/gen_winmm_proxy.py [path\\to\\winmm.dll]
writes: dll/winmm.def, dll/winmm_proxy.asm, dll/winmm_proxy.inc"""
import os, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_win = os.environ.get('SystemRoot', r'C:\Windows')
# a 32-bit Python sees SysWOW64 through 'System32'; 'Sysnative' reaches the real 64-bit folder
_sys = os.path.join(_win, 'Sysnative') if os.path.isdir(os.path.join(_win, 'Sysnative')) else os.path.join(_win, 'System32')
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(_sys, 'winmm.dll')

d = open(SRC, 'rb').read()
pe = struct.unpack_from('<I', d, 0x3C)[0]
nsec = struct.unpack_from('<H', d, pe + 6)[0]
optsz = struct.unpack_from('<H', d, pe + 20)[0]
opt = pe + 24
assert struct.unpack_from('<H', d, opt)[0] == 0x20B, 'expected a 64-bit winmm.dll'
secs = [struct.unpack_from('<IIII', d, opt + optsz + 40 * i + 8) for i in range(nsec)]  # vsz, va, rsz, raw


def off(rva):
    for vsz, va, rsz, raw in secs:
        if va <= rva < va + max(vsz, rsz):
            return raw + rva - va
    raise ValueError(hex(rva))


def cstr(rva):
    o = off(rva)
    return d[o:d.index(b'\0', o)].decode()


exp_rva = struct.unpack_from('<I', d, opt + 112)[0]
e = off(exp_rva)
base, nfun, nnam, afun, anam, aord = struct.unpack_from('<IIIIII', d, e + 16)
names = {}
for i in range(nnam):
    nm = cstr(struct.unpack_from('<I', d, off(anam) + 4 * i)[0])
    names[struct.unpack_from('<H', d, off(aord) + 2 * i)[0]] = nm
exports = []   # (ordinal, name or None)
for i in range(nfun):
    if struct.unpack_from('<I', d, off(afun) + 4 * i)[0]:   # skip empty slots
        exports.append((base + i, names.get(i)))
print('%s: %d exports (%d named)' % (SRC, len(exports), sum(1 for _, n in exports if n)))

hdr = '; generated by tools/gen_winmm_proxy.py from %s - do not edit\n' % os.path.basename(SRC)
with open(os.path.join(ROOT, 'dll', 'winmm.def'), 'w', newline='\r\n') as f:
    f.write(hdr + 'LIBRARY winmm\nEXPORTS\n')
    for i, (o, n) in enumerate(exports):
        f.write('    %s=wp_%d @%d\n' % (n, i, o) if n else '    wp_%d @%d NONAME\n' % (i, o))
with open(os.path.join(ROOT, 'dll', 'winmm_proxy.asm'), 'w', newline='\r\n') as f:
    f.write(hdr + 'EXTERN g_winmmFn:QWORD\n.code\n')
    for i in range(len(exports)):
        f.write('wp_%d PROC\n    jmp QWORD PTR [g_winmmFn + %d]\nwp_%d ENDP\n' % (i, 8 * i, i))
    f.write('END\n')
with open(os.path.join(ROOT, 'dll', 'winmm_proxy.inc'), 'w', newline='\r\n') as f:
    f.write(hdr.replace(';', '//'))
    f.write('static constexpr int WINMM_EXPORTS = %d;\n' % len(exports))
    f.write('struct WinmmExport { const char* name; unsigned short ordinal; };\n')
    f.write('static const WinmmExport WINMM_TABLE[WINMM_EXPORTS] = {\n')
    for o, n in exports:
        f.write('    { %s, %d },\n' % ('"%s"' % n if n else 'nullptr', o))
    f.write('};\n')
print('wrote dll/winmm.def, dll/winmm_proxy.asm, dll/winmm_proxy.inc')
